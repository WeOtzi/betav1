-- Guardia de columnas: el artista solo responde; el cliente solo retira la
-- disputa o edita su descripción/evidencia mientras está abierta; soporte resuelve.
create or replace function public.fn_quotation_disputes_guard()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  q record;
begin
  if public.is_support_user() then
    if new.status = 'resolved' and old.status is distinct from 'resolved' then
      new.resolved_at := coalesce(new.resolved_at, timezone('utc', now()));
      new.resolved_by := coalesce(new.resolved_by, uid);
    end if;
    new.updated_at := timezone('utc', now());
    return new;
  end if;

  select artist_id, client_user_id into q from public.quotations_db where id = old.quotation_id;

  if new.quotation_id is distinct from old.quotation_id
     or new.quote_id is distinct from old.quote_id
     or new.opened_by is distinct from old.opened_by
     or new.opened_by_role is distinct from old.opened_by_role
     or new.resolution is distinct from old.resolution
     or new.resolved_at is distinct from old.resolved_at
     or new.resolved_by is distinct from old.resolved_by
     or new.created_at is distinct from old.created_at then
    raise exception 'Solo soporte puede cambiar estos datos de la disputa';
  end if;

  if uid = q.artist_id then
    if new.status is distinct from old.status
       or new.title is distinct from old.title
       or new.description is distinct from old.description
       or new.evidence is distinct from old.evidence then
      raise exception 'El artista solo puede responder la disputa';
    end if;
    if new.artist_response is distinct from old.artist_response then
      new.artist_responded_at := timezone('utc', now());
    end if;
  elsif uid = q.client_user_id then
    if new.artist_response is distinct from old.artist_response
       or new.artist_responded_at is distinct from old.artist_responded_at then
      raise exception 'El cliente no puede editar la respuesta del artista';
    end if;
    if old.status <> 'open' or new.status not in ('open', 'withdrawn') then
      raise exception 'El cliente solo puede retirar una disputa abierta';
    end if;
  else
    raise exception 'Sin permiso sobre esta disputa';
  end if;

  new.updated_at := timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists trg_quotation_disputes_guard on public.quotation_disputes;
create trigger trg_quotation_disputes_guard
  before update on public.quotation_disputes
  for each row execute function public.fn_quotation_disputes_guard();

-- Sincroniza quotations_db.dispute_status ('none' | 'open' | 'resolved').
-- SECURITY DEFINER: el cliente que abre la disputa no tiene UPDATE sobre la
-- fila del artista; la función toca SOLO dispute_status.
create or replace function public.fn_quotation_disputes_sync_status()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  next_status text;
begin
  if exists (select 1 from public.quotation_disputes d
             where d.quotation_id = new.quotation_id and d.status = 'open') then
    next_status := 'open';
  elsif exists (select 1 from public.quotation_disputes d
                where d.quotation_id = new.quotation_id and d.status = 'resolved') then
    next_status := 'resolved';
  else
    next_status := 'none';
  end if;

  update public.quotations_db
     set dispute_status = next_status
   where id = new.quotation_id
     and dispute_status is distinct from next_status;
  return new;
end;
$$;

revoke all on function public.fn_quotation_disputes_sync_status() from public;

drop trigger if exists trg_quotation_disputes_sync_status on public.quotation_disputes;
create trigger trg_quotation_disputes_sync_status
  after insert or update of status on public.quotation_disputes
  for each row execute function public.fn_quotation_disputes_sync_status();

