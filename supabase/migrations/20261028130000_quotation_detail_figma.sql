-- ---------------------------------------------------------------------------
-- 3. Disputas sobre la entrega
-- ---------------------------------------------------------------------------
create table if not exists public.quotation_disputes (
  id bigint generated by default as identity primary key,
  quotation_id integer not null references public.quotations_db(id) on delete cascade,
  quote_id text not null,
  opened_by uuid not null default auth.uid(),
  opened_by_role text not null default 'client'
    check (opened_by_role in ('client', 'artist', 'support')),
  status text not null default 'open'
    check (status in ('open', 'resolved', 'withdrawn')),
  title text not null check (char_length(btrim(title)) between 3 and 160),
  description text not null default '' check (char_length(description) <= 4000),
  -- [{ "name": "reclamo-foto-01.jpg", "url": "https://..." }]
  evidence jsonb not null default '[]'::jsonb check (jsonb_typeof(evidence) = 'array'),
  artist_response text check (artist_response is null or char_length(artist_response) <= 4000),
  artist_responded_at timestamptz,
  resolution text check (resolution is null or char_length(resolution) <= 4000),
  resolved_at timestamptz,
  resolved_by uuid,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_quotation_disputes_quotation
  on public.quotation_disputes (quotation_id, created_at desc);
create unique index if not exists uq_quotation_disputes_one_open
  on public.quotation_disputes (quotation_id) where status = 'open';

alter table public.quotation_disputes enable row level security;

revoke all on table public.quotation_disputes from anon;
revoke all on table public.quotation_disputes from authenticated;
grant select, insert, update on table public.quotation_disputes to authenticated;

-- Partes de la cotización (artista o cliente registrado) y soporte.
drop policy if exists quotation_disputes_select_parties on public.quotation_disputes;
create policy quotation_disputes_select_parties on public.quotation_disputes
  for select to authenticated
  using (
    public.is_support_user()
    or exists (
      select 1 from public.quotations_db q
      where q.id = quotation_disputes.quotation_id
        and (q.artist_id = (select auth.uid()) or q.client_user_id = (select auth.uid()))
    )
  );

-- Solo el cliente de la cotización abre una disputa (o soporte en su nombre).
drop policy if exists quotation_disputes_insert_client on public.quotation_disputes;
create policy quotation_disputes_insert_client on public.quotation_disputes
  for insert to authenticated
  with check (
    public.is_support_user()
    or (
      opened_by = (select auth.uid())
      and opened_by_role = 'client'
      and status = 'open'
      and exists (
        select 1 from public.quotations_db q
        where q.id = quotation_disputes.quotation_id
          and q.quote_id = quotation_disputes.quote_id
          and q.client_user_id = (select auth.uid())
      )
    )
  );

-- Las partes pueden actualizar; el trigger de abajo acota QUÉ columnas.
drop policy if exists quotation_disputes_update_parties on public.quotation_disputes;
create policy quotation_disputes_update_parties on public.quotation_disputes
  for update to authenticated
  using (
    public.is_support_user()
    or exists (
      select 1 from public.quotations_db q
      where q.id = quotation_disputes.quotation_id
        and (q.artist_id = (select auth.uid()) or q.client_user_id = (select auth.uid()))
