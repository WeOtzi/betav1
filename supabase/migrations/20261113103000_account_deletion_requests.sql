revoke all on table public.account_deletion_events from anon, authenticated;
grant select on table public.account_deletion_requests to authenticated;
grant select on table public.account_deletion_events to authenticated;
grant all on table public.account_deletion_requests to service_role;
grant all on table public.account_deletion_events to service_role;
grant usage, select on sequence public.account_deletion_events_id_seq to service_role;

create or replace function public.account_deletion_touch()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists account_deletion_requests_touch on public.account_deletion_requests;
create trigger account_deletion_requests_touch
  before update on public.account_deletion_requests
  for each row execute function public.account_deletion_touch();

-- ---------------------------------------------------------------------------
-- Ítem de la lista de bloqueos.
--   severity: 'block' (impide aprobar/ejecutar), 'check' (no se pudo verificar
--   automáticamente: también bloquea, por las dudas) o 'warn' (informativo:
--   se cierra o se pierde al borrar, no impide).
-- ---------------------------------------------------------------------------
create or replace function public.account_deletion_item(
  p_code text, p_severity text, p_label text, p_detail text, p_count numeric, p_href text
) returns jsonb language sql immutable set search_path = public as $$
  select jsonb_build_object('code', p_code, 'severity', p_severity, 'label', p_label,
    'detail', p_detail, 'count', p_count, 'href', p_href);
$$;
revoke all on function public.account_deletion_item(text, text, text, text, numeric, text) from public;

-- Cálculo interno (sin chequeo de permisos: lo llaman las funciones de abajo).
-- Cada chequeo va en su propio bloque: si la tabla no existe en este entorno
-- (p. ej. la Store sin aplicar) se omite; si falta una columna, el ítem sale
-- como 'check' (verificar a mano) en lugar de romper toda la lista.
create or replace function public.account_deletion_blockers_internal(p_user_id uuid)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_items jsonb := '[]'::jsonb;
  v_n integer;
  v_txt text;
  v_studios uuid[] := '{}';
  v_is_artist boolean := false;
  v_is_client boolean := false;
begin
  if p_user_id is null then
    return v_items;
  end if;

  -- Cuentas protegidas: soporte y superadmin no se dan de baja por este flujo.
  begin
    if exists (select 1 from auth.users u where u.id = p_user_id and lower(coalesce(u.email, '')) = 'isai@weotzi.com') then
      v_items := v_items || public.account_deletion_item('protected_account', 'block', 'Cuenta protegida',
        'La cuenta superadmin no se puede eliminar.', 1, null);
    end if;
  exception when undefined_table or undefined_column then null;
  end;
  begin
    if exists (select 1 from public.support_users_db s where s.user_id = p_user_id and coalesce(s.is_active, true)) then
      v_items := v_items || public.account_deletion_item('support_account', 'block', 'Cuenta de soporte activa',
        'Primero hay que desactivar el acceso de soporte de esta cuenta.', 1, null);
    end if;
  exception when undefined_table then null;
    when undefined_column then
      v_items := v_items || public.account_deletion_item('support_account', 'check', 'Acceso de soporte',
        'No pudimos verificar si la cuenta tiene acceso de soporte.', null, null);
  end;

  begin
    v_is_artist := exists (select 1 from public.artists_db a where a.user_id = p_user_id);
  exception when undefined_table or undefined_column then v_is_artist := false;
  end;
  begin
    v_is_client := exists (select 1 from public.clients_db c where c.user_id = p_user_id);
  exception when undefined_table or undefined_column then v_is_client := false;
  end;
  begin
    v_is_client := v_is_client or exists (select 1 from public.client_profiles cp where cp.client_user_id = p_user_id);
  exception when undefined_table or undefined_column then null;
  end;
  begin
    select coalesce(array_agg(s.id), '{}') into v_studios from public.studios s where s.user_id = p_user_id;
  exception when undefined_table or undefined_column then v_studios := '{}';
  end;

  -- 1 · Disputas abiertas (como artista o como cliente).
  begin
    select count(*) into v_n
      from public.quotation_disputes d
      join public.quotations_db q on q.id = d.quotation_id
     where d.status = 'open' and (q.artist_id = p_user_id or q.client_user_id = p_user_id);
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('open_disputes', 'block', 'Disputas abiertas',
        v_n || ' disputa(s) sin resolver. Soporte tiene que cerrarlas antes de la baja.', v_n,
        case when v_is_artist then '/my-quotations' else '/client/dashboard#mis-cotizaciones' end);
    end if;
  exception when undefined_table then null;
    when undefined_column then
      v_items := v_items || public.account_deletion_item('open_disputes', 'check', 'Disputas',
        'No pudimos verificar las disputas automáticamente.', null, null);
  end;

  -- 2 · Trabajos en curso (cotización aprobada o en progreso).
  begin
    select count(*) into v_n
      from public.quotations_db q
     where (q.artist_id = p_user_id or q.client_user_id = p_user_id)
       and q.quote_status in ('client_approved', 'in_progress', 'en_progreso', 'artist_completed');
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('quotes_in_progress', 'block', 'Trabajos en curso',
        v_n || ' cotización(es) aprobada(s) o en progreso. Terminalas o cancelalas.', v_n,
        case when v_is_artist then '/my-quotations' else '/client/dashboard#mis-cotizaciones' end);
    end if;
    select count(*) into v_n
      from public.quotations_db q
     where (q.artist_id = p_user_id or q.client_user_id = p_user_id)
       and q.quote_status in ('pending', 'responded');
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('quotes_open', 'warn', 'Cotizaciones abiertas',
        v_n || ' cotización(es) sin aprobar: se cierran al eliminar la cuenta.', v_n,
        case when v_is_artist then '/my-quotations' else '/client/dashboard#mis-cotizaciones' end);
    end if;
  exception when undefined_table then null;
    when undefined_column then
      v_items := v_items || public.account_deletion_item('quotes_in_progress', 'check', 'Cotizaciones',
        'No pudimos verificar las cotizaciones automáticamente.', null, null);
  end;

  -- 3 · Sesiones futuras de cotizaciones.
  begin
    select count(*) into v_n
      from public.quotation_sessions s
      join public.quotations_db q on q.id = s.quotation_id
     where (q.artist_id = p_user_id or q.client_user_id = p_user_id)
       and s.session_date::date >= current_date
       and coalesce(lower(s.status), '') not in ('completed', 'cancelled', 'canceled', 'completada', 'cancelada');
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('upcoming_sessions', 'block', 'Sesiones agendadas',
        v_n || ' sesión(es) futura(s). Realizalas o cancelalas.', v_n,
        case when v_is_artist then '/calendar' else '/client/dashboard#mis-cotizaciones' end);
    end if;
  exception when undefined_table then null;
    when undefined_column or invalid_datetime_format or datetime_field_overflow then
      v_items := v_items || public.account_deletion_item('upcoming_sessions', 'check', 'Sesiones',
        'No pudimos verificar las sesiones agendadas automáticamente.', null, null);
  end;

  -- 4 · Wallet del artista: saldo disponible, retiros en proceso, cobros por liberar.
  begin
    select string_agg(t.currency || ' ' || to_char(t.bal, 'FM999G999G990D00'), ' · ' order by t.currency), count(*)
      into v_txt, v_n
      from (
        select m.currency, sum(case
          when m.kind in ('release', 'adjustment') and m.status = 'completed' then m.amount
          when m.kind = 'withdrawal' and m.status in ('processing', 'completed') then -m.amount
          when m.kind in ('fee', 'refund') and m.status = 'completed' then -m.amount
          else 0 end) as bal
        from public.artist_wallet_movements m
        where m.artist_user_id = p_user_id
        group by m.currency
      ) t
     where t.bal > 0;
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('wallet_balance', 'block', 'Saldo en el wallet',
        'Saldo disponible: ' || v_txt || '. Retiralo antes de la baja.', v_n, '/artist/account#cobros');
    end if;
    select count(*) into v_n from public.artist_wallet_movements m
     where m.artist_user_id = p_user_id and m.kind = 'withdrawal' and m.status = 'processing';
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('wallet_withdrawals', 'block', 'Retiros en proceso',
        v_n || ' retiro(s) todavía en proceso.', v_n, '/artist/account#cobros');
    end if;
    select count(*) into v_n from public.artist_wallet_movements m
     where m.artist_user_id = p_user_id and m.kind = 'payment'
       and m.status in ('pending_service', 'awaiting_release', 'blocked');
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('wallet_pending', 'block', 'Cobros por liberar',
        v_n || ' cobro(s) pendiente(s) de liberar o retenido(s).', v_n, '/artist/account#cobros');
    end if;
  exception when undefined_table then null;
    when undefined_column then
      v_items := v_items || public.account_deletion_item('wallet_balance', 'check', 'Wallet',
        'No pudimos verificar el saldo del wallet automáticamente.', null, null);
  end;

  -- 5 · Store: pedidos pendientes como comprador o como vendedor (artista o estudio).
  begin
    select count(*) into v_n from public.store_orders o
     where o.status in ('pending_payment', 'paid')
       and (o.buyer_user_id = p_user_id
         or (o.seller_type = 'artist' and o.seller_id = p_user_id)
         or (o.seller_type = 'studio' and o.seller_id = any (v_studios)));
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('store_orders', 'block', 'Pedidos de la Store pendientes',
        v_n || ' pedido(s) sin pagar o sin entregar.', v_n, '/store/purchases/');
    end if;
  exception when undefined_table then null;
    when undefined_column then
      v_items := v_items || public.account_deletion_item('store_orders', 'check', 'Store',
        'No pudimos verificar los pedidos de la Store automáticamente.', null, null);
  end;

  -- 6 · Membresías del artista en estudios (activas bloquean; invitaciones avisan).
  begin
    select count(*) into v_n from public.studio_artist_memberships m
     where m.artist_user_id = p_user_id and m.status in ('active', 'paused');
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('studio_memberships', 'block', 'Membresías en estudios',
        v_n || ' membresía(s) activa(s) en estudios. Finalizalas primero.', v_n, '/artist/account#perfil');
    end if;
    select count(*) into v_n from public.studio_artist_memberships m
     where m.artist_user_id = p_user_id and m.status in ('pending_invite', 'pending_acceptance');
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('studio_invitations', 'warn', 'Invitaciones de estudios',
        v_n || ' invitación(es) pendiente(s): se descartan al eliminar la cuenta.', v_n, null);
    end if;
  exception when undefined_table then null;
    when undefined_column then
      v_items := v_items || public.account_deletion_item('studio_memberships', 'check', 'Membresías',
        'No pudimos verificar las membresías en estudios automáticamente.', null, null);
  end;

  -- 7 · Contratos con estudios enviados o vigentes (como artista).
  begin
    select count(*) into v_n from public.studio_contracts c
     where c.artist_user_id = p_user_id and c.status in ('sent', 'signed', 'active');
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('studio_contracts', 'block', 'Contratos con estudios',
        v_n || ' contrato(s) enviado(s) o vigente(s).', v_n, null);
    end if;
  exception when undefined_table then null;
    when undefined_column then
      v_items := v_items || public.account_deletion_item('studio_contracts', 'check', 'Contratos',
        'No pudimos verificar los contratos con estudios automáticamente.', null, null);
  end;

  -- 8 · Reservas futuras en estudios (como artista o del estudio propio).
  begin
    select count(*) into v_n from public.studio_bookings b
     where b.status = 'confirmed' and b.starts_at >= now()
       and (b.artist_user_id = p_user_id or b.studio_id = any (v_studios));
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('studio_bookings', 'block', 'Reservas futuras en estudios',
        v_n || ' reserva(s) confirmada(s) por delante.', v_n,
        case when cardinality(v_studios) > 0 then '/studio/dashboard#ops' else '/calendar' end);
    end if;
  exception when undefined_table then null;
    when undefined_column then
      v_items := v_items || public.account_deletion_item('studio_bookings', 'check', 'Reservas en estudios',
        'No pudimos verificar las reservas en estudios automáticamente.', null, null);
  end;

  -- 9 · Estudio propio: equipo activo y contratos enviados a su equipo.
  if cardinality(v_studios) > 0 then
    begin
      select count(*) into v_n from public.studio_artist_memberships m
       where m.studio_id = any (v_studios) and m.status in ('active', 'paused')
         and m.artist_user_id <> p_user_id;
      if v_n > 0 then
        v_items := v_items || public.account_deletion_item('studio_roster', 'block', 'Equipo activo en tu estudio',
          v_n || ' artista(s) con membresía activa. Finalizá las membresías primero.', v_n, '/studio/dashboard#roster');
      end if;
    exception when undefined_table then null;
      when undefined_column then
        v_items := v_items || public.account_deletion_item('studio_roster', 'check', 'Equipo del estudio',
          'No pudimos verificar el equipo del estudio automáticamente.', null, null);
    end;
    begin
      select count(*) into v_n from public.studio_contracts c
        join public.studio_artist_memberships m on m.id = c.membership_id
       where m.studio_id = any (v_studios) and c.status in ('sent', 'signed', 'active');
      if v_n > 0 then
        v_items := v_items || public.account_deletion_item('studio_roster_contracts', 'block', 'Contratos del estudio',
          v_n || ' contrato(s) enviado(s) o vigente(s) con tu equipo.', v_n, '/studio/dashboard#roster');
      end if;
    exception when undefined_table then null;
      when undefined_column then
        v_items := v_items || public.account_deletion_item('studio_roster_contracts', 'check', 'Contratos del estudio',
          'No pudimos verificar los contratos del estudio automáticamente.', null, null);
    end;
  end if;

  -- 10 · Avisos (no bloquean).
  begin
    select count(*) into v_n from public.job_board_requests r
     where r.client_user_id = p_user_id and r.status = 'open';
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('job_board_requests', 'warn', 'Ideas publicadas en el Job Board',
        v_n || ' publicación(es) abierta(s): se cierran al eliminar la cuenta.', v_n, '/client/dashboard');
    end if;
  exception when undefined_table or undefined_column then null;
  end;
  begin
    select count(*) into v_n from public.job_board_applications a
     where a.artist_id = p_user_id and a.status in ('pending', 'viewed');
    if v_n > 0 then
      v_items := v_items || public.account_deletion_item('job_board_applications', 'warn', 'Postulaciones pendientes',
        v_n || ' postulación(es) sin respuesta: se retiran al eliminar la cuenta.', v_n, '/job-board');
    end if;
  exception when undefined_table or undefined_column then null;
  end;

  return v_items;
end;
$$;
revoke all on function public.account_deletion_blockers_internal(uuid) from public, anon, authenticated;
grant execute on function public.account_deletion_blockers_internal(uuid) to service_role;

-- ¿Algún ítem impide aprobar/ejecutar?
create or replace function public.account_deletion_has_blockers(p_items jsonb)
returns boolean language sql immutable set search_path = public as $$
  select exists (
    select 1 from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) e
    where e ->> 'severity' in ('block', 'check')
  );
$$;
revoke all on function public.account_deletion_has_blockers(jsonb) from public;
grant execute on function public.account_deletion_has_blockers(jsonb) to authenticated, service_role;

-- RPC pública: el usuario solo para sí mismo; soporte y service-role para cualquiera.
create or replace function public.account_deletion_blockers(p_user_id uuid)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
begin
  if p_user_id is null then
    raise exception 'Falta el usuario.' using errcode = '22023';
  end if;
  if not (p_user_id = auth.uid() or public.is_support_user() or coalesce(auth.role(), '') = 'service_role') then
    raise exception 'Solo podés consultar los bloqueos de tu propia cuenta.' using errcode = '42501';
  end if;
  return public.account_deletion_blockers_internal(p_user_id);
end;
$$;
revoke all on function public.account_deletion_blockers(uuid) from public, anon;
grant execute on function public.account_deletion_blockers(uuid) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Usuario: pedir la baja. Calcula bloqueos (foto) y NO borra nada.
-- ---------------------------------------------------------------------------
create or replace function public.request_account_deletion(p_role text, p_reason text default null)
returns public.account_deletion_requests
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_role text := lower(btrim(coalesce(p_role, '')));
  v_reason text := nullif(btrim(coalesce(p_reason, '')), '');
  v_has_role boolean := false;
  v_email text;
  v_name text;
  v_items jsonb;
  v_row public.account_deletion_requests;
begin
  if v_uid is null then
    raise exception 'Iniciá sesión para pedir la baja.' using errcode = '42501';
  end if;
  if v_role not in ('client', 'artist', 'studio') then
    raise exception 'Tipo de cuenta no válido.' using errcode = '22023';
  end if;
  if v_reason is not null and char_length(v_reason) > 1000 then
    raise exception 'El motivo puede tener hasta 1000 caracteres.' using errcode = '22023';
  end if;

  begin
    if v_role = 'artist' then
      select true, a.name into v_has_role, v_name from public.artists_db a where a.user_id = v_uid limit 1;
    elsif v_role = 'studio' then
      select true, s.name into v_has_role, v_name from public.studios s where s.user_id = v_uid limit 1;
    else
      select true, c.full_name into v_has_role, v_name from public.clients_db c where c.user_id = v_uid limit 1;
    end if;
  exception when undefined_table or undefined_column then v_has_role := false;
  end;
  if v_role = 'client' and not coalesce(v_has_role, false) then
    begin
      select true, nullif(btrim(concat_ws(' ', cp.first_name, cp.last_name)), '') into v_has_role, v_name
        from public.client_profiles cp where cp.client_user_id = v_uid limit 1;
    exception when undefined_table or undefined_column then v_has_role := false;
    end;
  end if;
  if not coalesce(v_has_role, false) then
    raise exception 'No encontramos una cuenta de ese tipo a tu nombre.' using errcode = '22023';
  end if;

  if exists (select 1 from public.account_deletion_requests r
              where r.user_id = v_uid and r.status in ('pending', 'in_review', 'blocked', 'approved')) then
    raise exception 'Ya tenés una solicitud de baja abierta.' using errcode = '23505';
  end if;

  select u.email into v_email from auth.users u where u.id = v_uid;
  v_items := public.account_deletion_blockers_internal(v_uid);

  insert into public.account_deletion_requests (
    user_id, role, reason, status, blockers, blockers_checked_at, email_snapshot, name_snapshot
  ) values (
    v_uid, v_role, v_reason, 'pending', v_items, now(), left(v_email, 320), left(v_name, 200)
  ) returning * into v_row;

  insert into public.account_deletion_events (request_id, actor_user_id, actor_role, action, to_status, detail)
  values (v_row.id, v_uid, 'user', 'requested', 'pending',
          jsonb_build_object('blocking', public.account_deletion_has_blockers(v_items), 'items', jsonb_array_length(v_items)));
  return v_row;
end;
$$;
revoke all on function public.request_account_deletion(text, text) from public, anon;
grant execute on function public.request_account_deletion(text, text) to authenticated;

-- Usuario: cancelar mientras no esté completada (ni cerrada).
create or replace function public.cancel_account_deletion(p_request_id uuid)
returns public.account_deletion_requests
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_row public.account_deletion_requests;
  v_from text;
begin
  if v_uid is null then
    raise exception 'Iniciá sesión para cancelar la solicitud.' using errcode = '42501';
  end if;
  select * into v_row from public.account_deletion_requests r where r.id = p_request_id for update;
  if not found or v_row.user_id <> v_uid then
    raise exception 'No encontramos esa solicitud.' using errcode = 'P0002';
  end if;
  if v_row.status not in ('pending', 'in_review', 'blocked', 'approved') then
    raise exception 'Esta solicitud ya está cerrada.' using errcode = '22023';
  end if;
  v_from := v_row.status;
  update public.account_deletion_requests
     set status = 'cancelled', cancelled_at = now()
   where id = p_request_id
   returning * into v_row;
  insert into public.account_deletion_events (request_id, actor_user_id, actor_role, action, from_status, to_status)
  values (v_row.id, v_uid, 'user', 'cancelled', v_from, 'cancelled');
  return v_row;
end;
$$;
revoke all on function public.cancel_account_deletion(uuid) from public, anon;
grant execute on function public.cancel_account_deletion(uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- Soporte: revisar. p_action ∈ in_review | blocked | approved | rejected | note | refresh.
-- Siempre recalcula y guarda los bloqueos. Aprobar exige cero bloqueos;
-- rechazar y marcar bloqueada exigen nota (la ve el usuario por email).
-- 'completed' NO se puede poner desde acá: solo el servidor al ejecutar.
-- ---------------------------------------------------------------------------
create or replace function public.support_review_account_deletion(
  p_request_id uuid, p_action text, p_note text default null
)
returns public.account_deletion_requests
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_action text := lower(btrim(coalesce(p_action, '')));
  v_note text := nullif(btrim(coalesce(p_note, '')), '');
  v_row public.account_deletion_requests;
  v_from text;
  v_to text;
  v_items jsonb;
begin
  if not public.is_support_user() then
    raise exception 'Solo soporte puede revisar bajas de cuenta.' using errcode = '42501';
  end if;
  if v_action not in ('in_review', 'blocked', 'approved', 'rejected', 'note', 'refresh') then
    raise exception 'Acción no válida.' using errcode = '22023';
  end if;
  if v_note is not null and char_length(v_note) > 2000 then
    raise exception 'La nota puede tener hasta 2000 caracteres.' using errcode = '22023';
  end if;
  select * into v_row from public.account_deletion_requests r where r.id = p_request_id for update;
  if not found then
    raise exception 'No encontramos esa solicitud.' using errcode = 'P0002';
  end if;
  if v_row.status not in ('pending', 'in_review', 'blocked', 'approved') then
    raise exception 'Esta solicitud ya está cerrada.' using errcode = '22023';
  end if;

  v_from := v_row.status;
  v_to := case when v_action in ('note', 'refresh') then v_row.status else v_action end;
  v_items := public.account_deletion_blockers_internal(v_row.user_id);

  if v_action = 'approved' and public.account_deletion_has_blockers(v_items) then
    raise exception 'Todavía hay bloqueos: no se puede aprobar la baja.' using errcode = '22023';
  end if;
  if v_action in ('rejected', 'blocked') and (v_note is null or char_length(v_note) < 5) then
    raise exception 'Escribí una nota para el usuario (mínimo 5 caracteres).' using errcode = '22023';
  end if;
  -- Una baja aprobada que vuelve a tener bloqueos se marca bloqueada sola.
  if v_to = 'approved' and v_action = 'refresh' and public.account_deletion_has_blockers(v_items) then
    v_to := 'blocked';
  end if;

  update public.account_deletion_requests
     set status = v_to,
         blockers = v_items,
         blockers_checked_at = now(),
         support_notes = coalesce(v_note, support_notes),
         reviewed_at = now(),
         reviewed_by = v_uid,
         decided_at = case when v_to in ('approved', 'rejected') and v_to <> v_from then now() else decided_at end
   where id = p_request_id
   returning * into v_row;

  insert into public.account_deletion_events (request_id, actor_user_id, actor_role, action, from_status, to_status, detail)
  values (v_row.id, v_uid, 'support', v_action, v_from, v_to,
          jsonb_build_object('note', v_note, 'blocking', public.account_deletion_has_blockers(v_items),
                             'items', jsonb_array_length(v_items)));
  return v_row;
end;
$$;
revoke all on function public.support_review_account_deletion(uuid, text, text) from public, anon;
grant execute on function public.support_review_account_deletion(uuid, text, text) to authenticated;

