-- ============================================================================
-- Ronda 3c · grupo "borrado": solicitudes de baja de cuenta gestionadas por
-- soporte (clientes, artistas y dueños de estudio).
--
--   · account_deletion_requests: una fila por solicitud. SIN FK a auth.users:
--     el registro sobrevive al borrado de la cuenta (auditoría mínima).
--     Una sola solicitud abierta por usuario (índice único parcial).
--   · account_deletion_events: registro de auditoría (quién, qué, cuándo).
--   · account_deletion_blockers(user_id): lista de bloqueos calculada en vivo
--     (disputas, wallet, trabajos en curso, sesiones futuras, Store, estudio…).
--     El usuario solo para sí mismo; soporte para cualquiera; service-role sí.
--   · request_account_deletion / cancel_account_deletion: lado del usuario.
--   · support_review_account_deletion: soporte (en revisión, bloqueada,
--     aprobada, rechazada, nota, recalcular). Aprobar exige cero bloqueos.
--   · El borrado real lo ejecuta SOLO el servidor (service-role) desde
--     POST /api/support/account-deletions/:id/execute. Nada se borra al pedir.
--
-- Aditiva e idempotente. La tabla vieja artist_account_deletion_requests
-- queda intacta (deprecada); sus filas se copian una vez (legacy_request_id).
-- Reversa: supabase/rollbacks/20261113103000_account_deletion_requests.down.sql
-- ============================================================================

create table if not exists public.account_deletion_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null,
  role text not null check (role in ('client', 'artist', 'studio')),
  reason text check (reason is null or char_length(reason) <= 1000),
  status text not null default 'pending'
    check (status in ('pending', 'in_review', 'blocked', 'approved', 'completed', 'cancelled', 'rejected')),
  support_notes text check (support_notes is null or char_length(support_notes) <= 2000),
  blockers jsonb not null default '[]'::jsonb check (jsonb_typeof(blockers) = 'array'),
  blockers_checked_at timestamptz,
  email_snapshot text check (email_snapshot is null or char_length(email_snapshot) <= 320),
  name_snapshot text check (name_snapshot is null or char_length(name_snapshot) <= 200),
  legacy_request_id uuid unique,
  requested_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid,
  decided_at timestamptz,
  cancelled_at timestamptz,
  completed_at timestamptz,
  completed_by uuid,
  updated_at timestamptz not null default now()
);

create unique index if not exists account_deletion_one_open_per_user
  on public.account_deletion_requests (user_id)
  where status in ('pending', 'in_review', 'blocked', 'approved');
create index if not exists account_deletion_requests_status_idx
  on public.account_deletion_requests (status, requested_at desc);

create table if not exists public.account_deletion_events (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.account_deletion_requests (id) on delete cascade,
  actor_user_id uuid,
  actor_role text not null check (actor_role in ('user', 'support', 'system')),
  action text not null check (char_length(action) between 1 and 40),
  from_status text,
  to_status text,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists account_deletion_events_request_idx
  on public.account_deletion_events (request_id, created_at);

alter table public.account_deletion_requests enable row level security;
alter table public.account_deletion_events enable row level security;

drop policy if exists account_deletion_requests_owner_read on public.account_deletion_requests;
create policy account_deletion_requests_owner_read on public.account_deletion_requests
  for select to authenticated
  using ((select auth.uid()) = user_id or public.is_support_user());

drop policy if exists account_deletion_events_support_read on public.account_deletion_events;
create policy account_deletion_events_support_read on public.account_deletion_events
  for select to authenticated using (public.is_support_user());

-- Escrituras SOLO por RPC security definer (o service-role desde el servidor).
